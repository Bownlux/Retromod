package com.retromod.inplace;

import com.google.gson.GsonBuilder;
import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import com.retromod.util.JsonSecurity;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.AtomicMoveNotSupportedException;
import java.nio.file.Files;
import java.nio.file.LinkOption;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.TreeMap;
import java.util.regex.Pattern;

/**
 * The cache's {@code index.json}: entries by source SHA-256, the stamp they belong to, and a
 * hash memo so unchanged originals are not reread on every launch.
 *
 * <p>The index lives next to the stamped {@code jars/} folder, not inside it, so a stamp wipe
 * can never delete it while another step of the same pass still needs it. Entries are only
 * trusted when {@link #stamp()} matches the {@code jars/} folder's stamp.
 *
 * <p>Reading is strict. A file name with a path separator, an unknown status, or a malformed
 * hash makes the whole index invalid, and the cache starts over rather than serving from it.
 */
final class CacheIndex {

    static final int FORMAT = 1;
    static final long MAX_INDEX_BYTES = 8L * 1024 * 1024;

    private static final Pattern SHA256 = Pattern.compile("[0-9a-f]{64}");
    private static final Pattern FILE_NAME = Pattern.compile("[A-Za-z0-9._+-]{1,200}\\.jar");

    private String stamp;
    private final Map<String, CacheEntry> entries = new TreeMap<>();
    private final Map<String, Memo> memo = new TreeMap<>();

    /** Remembered hash of one original, valid while its fingerprint is unchanged. */
    record Memo(String fingerprint, String sha256) {}

    CacheIndex(String stamp) {
        this.stamp = stamp;
    }

    String stamp() {
        return stamp;
    }

    Map<String, CacheEntry> entries() {
        return entries;
    }

    Map<String, Memo> memo() {
        return memo;
    }

    /** Drops every entry and memo row and adopts {@code newStamp}. */
    void reset(String newStamp) {
        stamp = newStamp;
        entries.clear();
        memo.clear();
    }

    static boolean isSha256(String value) {
        return value != null && SHA256.matcher(value).matches();
    }

    /** Cache file names are generated by Retromod; anything else in the index is refused. */
    static boolean isCacheFileName(String value) {
        return value != null && FILE_NAME.matcher(value).matches()
                && !value.startsWith(".");
    }

    static CacheIndex read(Path file) throws IOException {
        String json = JsonSecurity.readUtf8(file, MAX_INDEX_BYTES,
                JsonSecurity.DEFAULT_MAX_DEPTH, "Retromod cache index");
        JsonElement parsed = JsonParser.parseString(json);
        if (!parsed.isJsonObject()) throw new IOException("Cache index is not a JSON object");
        JsonObject root = parsed.getAsJsonObject();
        if (intValue(root, "format") != FORMAT) {
            throw new IOException("Cache index has an unknown format");
        }
        CacheIndex index = new CacheIndex(requiredString(root, "stamp"));
        JsonObject entries = object(root, "entries");
        for (Map.Entry<String, JsonElement> row : entries.entrySet()) {
            if (!isSha256(row.getKey()) || !row.getValue().isJsonObject()) {
                throw new IOException("Cache index has an invalid entry key: " + row.getKey());
            }
            index.entries.put(row.getKey(), readEntry(row.getKey(),
                    row.getValue().getAsJsonObject()));
        }
        JsonObject memo = object(root, "memo");
        for (Map.Entry<String, JsonElement> row : memo.entrySet()) {
            if (!row.getValue().isJsonObject()) {
                throw new IOException("Cache index has an invalid memo row");
            }
            JsonObject value = row.getValue().getAsJsonObject();
            String sha = requiredString(value, "sha256");
            if (!isSha256(sha)) throw new IOException("Cache index memo has an invalid hash");
            index.memo.put(row.getKey(), new Memo(requiredString(value, "fingerprint"), sha));
        }
        return index;
    }

    private static CacheEntry readEntry(String sha, JsonObject value) throws IOException {
        CacheEntry.Status status;
        try {
            status = CacheEntry.Status.valueOf(
                    requiredString(value, "status").toUpperCase(Locale.ROOT));
        } catch (IllegalArgumentException e) {
            throw new IOException("Cache index has an unknown status for " + sha);
        }
        String file = optionalString(value, "file");
        String fileSha = optionalString(value, "fileSha256");
        if (file != null && !isCacheFileName(file)) {
            throw new IOException("Cache index names an unsafe file: " + file);
        }
        if (fileSha != null && !isSha256(fileSha)) {
            throw new IOException("Cache index has an invalid file hash for " + sha);
        }
        if (status == CacheEntry.Status.OK && (file == null || fileSha == null)) {
            throw new IOException("Cache index has an OK entry without a file: " + sha);
        }
        List<String> modIds = new ArrayList<>();
        if (value.has("modIds")) {
            if (!value.get("modIds").isJsonArray()) {
                throw new IOException("Cache index has invalid mod ids for " + sha);
            }
            for (JsonElement id : value.getAsJsonArray("modIds")) {
                if (!id.isJsonPrimitive() || !id.getAsJsonPrimitive().isString()) {
                    throw new IOException("Cache index has an invalid mod id for " + sha);
                }
                modIds.add(id.getAsString());
            }
        }
        return new CacheEntry(sha, status, file, fileSha,
                optionalString(value, "fileFingerprint"), modIds,
                optionalString(value, "modVersion"), optionalString(value, "sourceName"),
                optionalString(value, "sourceLocation"), longValue(value, "sourceSize"),
                optionalString(value, "failure"), intValue(value, "attempts"),
                optionalString(value, "retromodVersion"), longValue(value, "updated"));
    }

    /** Writes the index through a sibling temporary file and an atomic rename. */
    void write(Path file) throws IOException {
        JsonObject root = new JsonObject();
        root.addProperty("format", FORMAT);
        root.addProperty("stamp", stamp);
        JsonObject entryRows = new JsonObject();
        for (CacheEntry entry : entries.values()) {
            entryRows.add(entry.sourceSha256(), writeEntry(entry));
        }
        root.add("entries", entryRows);
        JsonObject memoRows = new JsonObject();
        for (Map.Entry<String, Memo> row : memo.entrySet()) {
            JsonObject value = new JsonObject();
            value.addProperty("fingerprint", row.getValue().fingerprint());
            value.addProperty("sha256", row.getValue().sha256());
            memoRows.add(row.getKey(), value);
        }
        root.add("memo", memoRows);

        String json = new GsonBuilder().setPrettyPrinting().disableHtmlEscaping()
                .create().toJson(root) + "\n";
        Path parent = file.getParent();
        Path staged = Files.createTempFile(parent, ".index-", ".tmp");
        try {
            Files.writeString(staged, json, StandardCharsets.UTF_8);
            if (Files.isSymbolicLink(file)
                    || (Files.exists(file, LinkOption.NOFOLLOW_LINKS)
                            && !Files.isRegularFile(file, LinkOption.NOFOLLOW_LINKS))) {
                throw new IOException("Cache index is not a regular file: " + file);
            }
            try {
                Files.move(staged, file, StandardCopyOption.ATOMIC_MOVE,
                        StandardCopyOption.REPLACE_EXISTING);
            } catch (AtomicMoveNotSupportedException e) {
                Files.move(staged, file, StandardCopyOption.REPLACE_EXISTING);
            }
        } finally {
            Files.deleteIfExists(staged);
        }
    }

    private static JsonObject writeEntry(CacheEntry entry) {
        JsonObject value = new JsonObject();
        value.addProperty("status", entry.status().name().toLowerCase(Locale.ROOT));
        addIfPresent(value, "file", entry.file());
        addIfPresent(value, "fileSha256", entry.fileSha256());
        addIfPresent(value, "fileFingerprint", entry.fileFingerprint());
        JsonArray ids = new JsonArray();
        entry.modIds().forEach(ids::add);
        value.add("modIds", ids);
        addIfPresent(value, "modVersion", entry.modVersion());
        addIfPresent(value, "sourceName", entry.sourceName());
        addIfPresent(value, "sourceLocation", entry.sourceLocation());
        value.addProperty("sourceSize", entry.sourceSize());
        addIfPresent(value, "failure", entry.failure());
        value.addProperty("attempts", entry.attempts());
        addIfPresent(value, "retromodVersion", entry.retromodVersion());
        value.addProperty("updated", entry.updated());
        return value;
    }

    private static void addIfPresent(JsonObject object, String key, String value) {
        if (value != null) object.addProperty(key, value);
    }

    private static JsonObject object(JsonObject root, String key) throws IOException {
        if (!root.has(key)) return new JsonObject();
        if (!root.get(key).isJsonObject()) throw new IOException("Cache index '" + key
                + "' is not an object");
        return root.getAsJsonObject(key);
    }

    private static String requiredString(JsonObject object, String key) throws IOException {
        String value = optionalString(object, key);
        if (value == null) throw new IOException("Cache index is missing '" + key + "'");
        return value;
    }

    private static String optionalString(JsonObject object, String key) throws IOException {
        if (!object.has(key) || object.get(key).isJsonNull()) return null;
        JsonElement value = object.get(key);
        if (!value.isJsonPrimitive() || !value.getAsJsonPrimitive().isString()) {
            throw new IOException("Cache index '" + key + "' is not a string");
        }
        return value.getAsString();
    }

    private static long longValue(JsonObject object, String key) throws IOException {
        if (!object.has(key)) return 0;
        JsonElement value = object.get(key);
        if (!value.isJsonPrimitive() || !value.getAsJsonPrimitive().isNumber()) {
            throw new IOException("Cache index '" + key + "' is not a number");
        }
        return value.getAsLong();
    }

    private static int intValue(JsonObject object, String key) throws IOException {
        long value = longValue(object, key);
        if (value < Integer.MIN_VALUE || value > Integer.MAX_VALUE) {
            throw new IOException("Cache index '" + key + "' is out of range");
        }
        return (int) value;
    }
}
