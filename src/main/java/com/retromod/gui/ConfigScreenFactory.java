/** In-game settings screen for Retromod: a grid of ON/OFF toggle rows and a Done button. */
public final class ConfigScreenFactory {

    private static final Logger LOGGER = LoggerFactory.getLogger("Retromod");
    private static final Path CONFIG_PATH = Path.of("config/retromod/config.json");
    private static final long MAX_CONFIG_BYTES = 1024L * 1024;

    // Cached MC classes. All Minecraft access is reflective, so this compiles without Minecraft
    // on the classpath.
    private static Class<?> screenClass;
    private static Class<?> textClass;
    private static Class<?> buttonWidgetClass;
    private static Class<?> pressActionClass;
    private static boolean resolved;

    /**
     * Boolean config keys in display order. The visible label for each row
     * comes from the translation key {@code retromod.settings.<key>}, so
     * these are just the config.json keys; labels live in lang files.
     */
    private static final String[] TOGGLE_KEYS = {
        "use_aot",
        "polyfills_enabled",
        "verify_transforms",
        InPlaceSettings.KEY,
    };

    // What the runtime uses when config.json lacks a key. A config written before a key existed
    // lacks it, so the screen must show this value, not the value a new file would carry.
    private static final Map<String, Boolean> RUNTIME_DEFAULTS = Map.of(
        "use_aot", true,
        "polyfills_enabled", true,
        "verify_transforms", false,
        InPlaceSettings.KEY, InPlaceSettings.DEFAULT_WRITE_TRANSLATED_JARS
    );

    /** Shown under the toggles while the saved in-place switch waits for a restart. */
    private static final String NEXT_LAUNCH_KEY = "retromod.settings.next_launch";

    private ConfigScreenFactory() {}

    /** Opens the in-game settings screen and returns to {@code parentScreen} on close. */
    public static void open(Object parentScreen) {
        if (!resolveClasses()) {
            LOGGER.warn("Cannot open Retromod settings because the required Minecraft GUI "
                    + "classes are unavailable");
            return;
        }

        final Map<String, Boolean> config = loadConfig();

        Object title = McI18n.translatable("retromod.settings.title");
        if (title == null) return;

        // The screen is a subclass generated by ScreenClassGenerator. Minecraft invokes the setup
        // callback on its render thread, so building and changing widgets there is safe.
        Object screen = ScreenClassGenerator.createScreen(
                title,
                s -> addAllWidgets(s, config, parentScreen),
                closeTo(parentScreen)
        );

        if (screen != null) {
            setScreen(screen);
        }
    }

    /** What Escape does: return to the parent screen like Done. */
    private static Runnable closeTo(Object parentScreen) {
        // Each toggle saved its own key when pressed, so closing writes nothing.
        return () -> setScreen(parentScreen);
    }

    // WIDGET LAYOUT

    /**
     * Called from the generated screen's init(). Adds one toggle row per
     * config option plus a Done button at the bottom.
     */
    private static void addAllWidgets(Object screen,
                                       Map<String, Boolean> config,
                                       Object parentScreen) {
        try {
            int width  = McReflect.getIntField(screen, screenClass, 854, "width", "field_22789");
            int height = McReflect.getIntField(screen, screenClass, 480, "height", "field_22790");

            // The bottom area is reserved for the Done button so toggle rows
            // can never overlap it. Available content height = whatever's
            // left between the top margin and the Done band. If the toggles
            // don't fit, we tighten the row spacing so they always do.
            int topMargin    = 30;   // below title
            int bottomMargin = 8;    // gap above screen edge
            int doneHeight   = 20;
            int doneGap      = 8;    // gap between content and Done button
            int statusHeight = 16;   // authenticity status line above Done
            int statusGap    = 4;

            int doneY = height - bottomMargin - doneHeight;
            int statusY = doneY - statusGap - statusHeight;
            int contentTop = topMargin;
            int contentBottom = statusY - doneGap; // status band is reserved like Done
            int contentH = Math.max(50, contentBottom - contentTop);

            int rowWidth   = 300;
            int labelWidth = 200;
            int toggleWidth = rowWidth - labelWidth - 4;
            int startX = width / 2 - rowWidth / 2;

            // The rows this game shows, plus a note row while the in-place switch waits for a restart.
            List<String> toggleKeys = visibleToggleKeys(System.getProperties());
            boolean waitsForRestart = switchWaitsForRestart(config, System.getProperties());

            // Tighten row height/spacing so all toggles fit in contentH
            // without requiring a scroll bar.
            int totalRows = toggleKeys.size() + (waitsForRestart ? 1 : 0);
            int desiredRowH = 20;
            int desiredSpacing = 4;
            int rowH;
            int rowSpacing;
            int desiredTotal = totalRows * (desiredRowH + desiredSpacing);
            if (desiredTotal <= contentH) {
                rowH = desiredRowH;
                rowSpacing = desiredSpacing;
            } else {
                // Squeeze: shrink height first, then spacing
                int unitsAvail = contentH / totalRows;
                rowH = Math.max(12, Math.min(desiredRowH, unitsAvail - 2));
                rowSpacing = Math.max(1, unitsAvail - rowH);
            }

            // (No action row: Choose Mods / Open retromod-input/ live in the
            // main Retromod screen; this is the settings-only screen.)

            for (int i = 0; i < toggleKeys.size(); i++) {
                final String key = toggleKeys.get(i);
                int rowY = contentTop + i * (rowH + rowSpacing);

                Object labelText = McI18n.translatable("retromod.settings." + key);
                Object labelBtn = buildButton(labelText,
                        makePressAction(() -> toggleAndRebuild(screen, config, parentScreen, key)),
                        startX, rowY, labelWidth, rowH);
                addWidget(screen, labelBtn);

                boolean value = config.getOrDefault(key, false);
                Object toggleText = McI18n.translatable(
                        value ? "retromod.settings.on" : "retromod.settings.off");
                Object toggleBtn = buildButton(toggleText,
                        makePressAction(() -> toggleAndRebuild(screen, config, parentScreen, key)),
                        startX + labelWidth + 4, rowY, toggleWidth, rowH);
                addWidget(screen, toggleBtn);
            }

            // A label row saying the in-place change takes effect at the next launch.
            if (waitsForRestart) {
                int noteY = contentTop + toggleKeys.size() * (rowH + rowSpacing);
                Object note = buildButton(McI18n.translatable(NEXT_LAUNCH_KEY),
                        makePressAction(() -> { }), startX, noteY, rowWidth, rowH);
                addWidget(screen, note);
            }

            // The lang value carries the § color codes. verify() is cached after the startup
            // verifyAndLog(), so no I/O happens on the render thread. Pressing does nothing.
            Object statusText = McI18n.translatable(statusKey(SignatureVerifier.verify().status()));
            if (statusText != null) {
                Object statusRow = buildButton(statusText,
                        makePressAction(() -> { }),
                        width / 2 - rowWidth / 2, statusY, rowWidth, statusHeight);
                addWidget(screen, statusRow);
            }

            Object doneBtn = buildButton(McI18n.translatable("retromod.settings.done"),
                    makePressAction(() -> setScreen(parentScreen)),
                    width / 2 - 75, doneY, 150, doneHeight);
            addWidget(screen, doneBtn);

        } catch (Exception e) {
            LOGGER.warn("Could not add config widgets: {}", e.getMessage());
        }
    }

    /** The toggle rows this game shows. */
    static List<String> visibleToggleKeys(Properties properties) {
        List<String> keys = new ArrayList<>(List.of(TOGGLE_KEYS));
        if (InPlaceSettings.switchApplies(properties)) {
            // Only the Fabric and Quilt entry point reads use_aot, so Forge and NeoForge hide it.
            keys.remove("use_aot");
        } else {
            // The in-place switch shows only where the Forge or NeoForge bootstrap loaded Retromod.
            // Fabric and Quilt always write translated jars into mods/.
            keys.remove(InPlaceSettings.KEY);
        }
        return keys;
    }

    /** The lang key of the build status line for each verification result. */
    static String statusKey(SignatureVerifier.Status status) {
        return switch (status) {
            case VERIFIED -> "retromod.settings.status.verified";
            case MODIFIED -> "retromod.settings.status.modified";
            case IMPOSTOR -> "retromod.settings.status.impostor";
            case UNKNOWN -> "retromod.settings.status.unknown";
        };
    }

    /** True when the saved in-place switch differs from what this launch runs. */
    static boolean switchWaitsForRestart(Map<String, Boolean> config, Properties properties) {
        // The discovery pass reads the switch only at startup, so a change waits for the next launch.
        Optional<Boolean> running = InPlaceSettings.writesTranslatedJarsThisLaunch(properties);
        boolean saved = config.getOrDefault(InPlaceSettings.KEY,
                InPlaceSettings.DEFAULT_WRITE_TRANSLATED_JARS);
        return running.isPresent() && running.get() != saved;
    }

    /**
     * Toggle a value, save, and rebuild the screen (simplest way to update
     * button labels since MC button messages vary across versions).
     */
    private static void toggleAndRebuild(Object screen,
                                          Map<String, Boolean> config,
                                          Object parentScreen,
                                          String key) {
        boolean newVal = !config.getOrDefault(key, false);
        config.put(key, newVal);
        // Only the pressed key is written, so a value the screen could not read stays as it is.
        saveSetting(CONFIG_PATH, key, newVal);

        // Re-open the screen to refresh button labels; runs on render thread
        // because the press action is dispatched by MC on the render thread.
        Object title = McI18n.translatable("retromod.settings.title");
        Object fresh = ScreenClassGenerator.createScreen(
                title,
                s -> addAllWidgets(s, config, parentScreen),
                closeTo(parentScreen)
        );
        if (fresh != null) setScreen(fresh);
    }

    // BUTTON BUILDERS

    /**
     * Build a button whose label is a pre-constructed Text/Component.
     * Callers pass a translatable Text from {@link McI18n} so the label
     * localizes correctly at render time.
     */
    private static Object buildButton(Object text, Object pressAction,
                                       int x, int y, int w, int h) {
        try {
            if (text == null || pressAction == null) return null;

            Method builderMethod = McReflect.findMethod(buttonWidgetClass,
                    new Class[]{textClass, pressActionClass}, "builder", "method_46430");
            if (builderMethod == null) return null;

            Object builder = builderMethod.invoke(null, text, pressAction);

            Method dim = McReflect.findMethod(builder.getClass(),
                    new Class[]{int.class, int.class, int.class, int.class},
                    "dimensions", "bounds", "method_46434", "pos");
            if (dim != null) builder = dim.invoke(builder, x, y, w, h);

            Method buildMethod = McReflect.findMethod(builder.getClass(), "build", "method_46431");
            if (buildMethod == null) return null;
            return buildMethod.invoke(builder);
        } catch (Exception e) {
            LOGGER.debug("Could not build button: {}", e.getMessage());
            return null;
        }
    }

    private static Object makePressAction(Runnable onPress) {
        if (pressActionClass == null) return null;
        return Proxy.newProxyInstance(
                pressActionClass.getClassLoader(),
                new Class<?>[]{pressActionClass},
                (proxy, method, args) -> {
                    if (method.getDeclaringClass() != Object.class) {
                        onPress.run();
                    }
                    return null;
                });
    }

    private static void addWidget(Object screen, Object widget) {
        if (widget == null) return;
        try {
            Method add = McReflect.findMethod(screenClass,
                    "addDrawableChild", "addRenderableWidget", "method_37063", "addWidget");
            if (add != null) {
                add.setAccessible(true);
                add.invoke(screen, widget);
            }
        } catch (Exception e) {
            LOGGER.debug("Could not add widget: {}", e.getMessage());
        }
    }

    // CONFIG I/O

    static Map<String, Boolean> loadConfig() {
        return loadConfig(CONFIG_PATH);
    }

    /** Reads each toggle with the runtime's reader and default, so the screen shows what runs. */
    static Map<String, Boolean> loadConfig(Path configPath) {
        Map<String, Boolean> config = new LinkedHashMap<>();
        for (String key : TOGGLE_KEYS) {
            config.put(key, RetromodConfig.getBooleanIfPresent(
                    configPath, key, RUNTIME_DEFAULTS.get(key)));
        }
        return config;
    }

    /** Writes one setting into config.json and keeps every other key as it is. */
    static void saveSetting(Path configPath, String key, boolean value) {
        Path folder = configPath.toAbsolutePath().getParent();
        try {
            Files.createDirectories(folder);
            String existing = Files.exists(configPath)
                    ? JsonSecurity.readUtf8(configPath, MAX_CONFIG_BYTES,
                            JsonSecurity.DEFAULT_MAX_DEPTH, "Retromod config")
                    : "";
            String merged = mergeConfigJson(existing, Map.of(key, value));
            // Write a temporary file first, so a failed write never leaves half a config.
            Path temp = Files.createTempFile(folder, ".config.json.", ".tmp");
            try {
                Files.writeString(temp, merged);
                try {
                    Files.move(temp, configPath, StandardCopyOption.ATOMIC_MOVE,
                            StandardCopyOption.REPLACE_EXISTING);
                } catch (AtomicMoveNotSupportedException e) {
                    Files.move(temp, configPath, StandardCopyOption.REPLACE_EXISTING);
                }
            } finally {
                Files.deleteIfExists(temp);
            }
        } catch (Exception e) {
            LOGGER.warn("Retromod could not save {} to {}: {}. Check that the folder is writable, "
                    + "or set the value in the file by hand.", key, configPath, e.getMessage());
        }
    }

    static String mergeConfigJson(String existing, Map<String, Boolean> config) {
        JsonObject root = new JsonObject();
        if (existing != null && !existing.isBlank()) {
            try {
                JsonSecurity.validate(existing, MAX_CONFIG_BYTES,
                        JsonSecurity.DEFAULT_MAX_DEPTH, "Retromod config");
                var parsed = JsonParser.parseString(existing);
                if (parsed.isJsonObject()) root = parsed.getAsJsonObject();
            } catch (Exception ignored) {
                // Invalid JSON is replaced with a clean, usable config.
            }
        }
        if (!root.has("_comment")) {
            root.addProperty("_comment",
                    "Retromod Configuration - https://github.com/Bownlux/Retromod");
        }
        for (var entry : config.entrySet()) {
            root.addProperty(entry.getKey(), entry.getValue());
        }
        return new GsonBuilder().setPrettyPrinting().create().toJson(root) + "\n";
    }

    // MC CLASS RESOLUTION

    private static boolean resolveClasses() {
        if (resolved) return screenClass != null;
        resolved = true;

        screenClass = McReflect.findClass(
            "net.minecraft.client.gui.screen.Screen",
            "net.minecraft.client.gui.screens.Screen",
            "net.minecraft.class_437"  // intermediary, pre-26.1 Fabric
        );
        textClass = McReflect.findClass(
            "net.minecraft.text.Text",
            "net.minecraft.network.chat.Component",
            "net.minecraft.class_2561"
        );
        buttonWidgetClass = McReflect.findClass(
            "net.minecraft.client.gui.widget.ButtonWidget",
            "net.minecraft.client.gui.components.Button",
            "net.minecraft.class_4185"
        );

        // Named first, because Button's other one-method interface is CreateNarration.
        pressActionClass = McReflect.findClass(
            "net.minecraft.client.gui.widget.ButtonWidget$PressAction",
            "net.minecraft.client.gui.components.Button$OnPress",
            "net.minecraft.class_4185$class_4241"
        );
        if (pressActionClass == null && buttonWidgetClass != null) {
            for (Class<?> inner : buttonWidgetClass.getDeclaredClasses()) {
                if (inner.isInterface() && inner.getMethods().length <= 2) {
                    pressActionClass = inner;
                    break;
                }
            }
        }

        return screenClass != null && textClass != null && buttonWidgetClass != null;
    }

    private static void setScreen(Object screen) {
        McScreens.show(screen);
    }
}
