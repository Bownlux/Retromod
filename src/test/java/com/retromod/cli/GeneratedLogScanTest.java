package com.retromod.cli;

import com.retromod.core.RetromodTransformer;
import com.retromod.core.RetromodVersion;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.objectweb.asm.ClassReader;
import org.objectweb.asm.ClassVisitor;
import org.objectweb.asm.MethodVisitor;
import org.objectweb.asm.Opcodes;

import java.lang.reflect.Field;
import java.lang.reflect.Method;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Retromod's generated classes warn through the game's logger. Standard error never reaches
 * {@code latest.log} on Forge and NeoForge, and Fabric logs it as INFO, so a warning printed there
 * was the only record of a dropped feature and was easy to lose.
 */
class GeneratedLogScanTest {

    private static final List<String> LOADERS = List.of("fabric", "forge", "neoforge");
    private static final List<String> HOSTS = List.of("1.20.1", "1.21.1", "26.2", "26.3");

    private final RetromodTransformer transformer = RetromodTransformer.getInstance();
    private Field cliTarget;
    private String savedCliTarget;
    private String savedTarget;

    @BeforeEach
    void saveTargets() throws Exception {
        cliTarget = RetromodCli.class.getDeclaredField("TARGET_MC_VERSION");
        cliTarget.setAccessible(true);
        savedCliTarget = (String) cliTarget.get(null);
        savedTarget = RetromodVersion.TARGET_MC_VERSION;
    }

    @AfterEach
    void restoreTargets() throws Exception {
        cliTarget.set(null, savedCliTarget);
        RetromodVersion.TARGET_MC_VERSION = savedTarget;
        transformer.clearRedirectsForTesting();
    }

    @Test
    @DisplayName("No generated class a shim registers prints to standard error or output")
    void registeredGeneratedClassesLogThroughTheGameLogger() throws Exception {
        List<String> hits = new ArrayList<>();
        for (String host : HOSTS) {
            for (String loader : LOADERS) {
                cliTarget.set(null, host);
                RetromodVersion.TARGET_MC_VERSION = host;
                transformer.clearRedirectsForTesting();
                RetromodCli.registerAllShimsGated(transformer, loader);
                for (Map.Entry<String, byte[]> synthetic : transformer.getSyntheticClasses().entrySet()) {
                    // Compiled helpers ship as classes and are a separate change; only generated bytes count here.
                    if (isCompiledHelper(synthetic.getKey())) continue;
                    scan(loader + " " + host + ": " + synthetic.getKey(), synthetic.getValue(), hits);
                }
            }
        }
        assertTrue(hits.isEmpty(), "generated classes must warn through GeneratedLog, not standard streams:\n"
                + String.join("\n", hits));
    }

    @Test
    @DisplayName("Generators that no shim registers offline also log through the game logger")
    void directGeneratorsLogThroughTheGameLogger() throws Exception {
        List<String> hits = new ArrayList<>();
        scan("EventHolderSpec", new com.retromod.loaderapi.fabric.v26.synth.EventHolderSpec("test/Holder",
                List.of(new com.retromod.loaderapi.fabric.v26.synth.EventHolderSpec.EventField(
                        "EVENT", "host.Owner", "EVENT"))).generate(), hits);
        scan("SamBridgeSynthetics.eventHolder", (byte[]) packagePrivate(
                "com.retromod.shim.api.fabric.SamBridgeSynthetics", "eventHolder")
                .invoke(null, "test/OldHolder", new String[][]{{"EVENT", "host.Owner", "EVENT"}}), hits);
        Class<?> lootEvents = Class.forName("com.retromod.shim.fabric.Pre1_20_5LootTableEventsBridge");
        Field callbacks = lootEvents.getDeclaredField("CALLBACKS");
        callbacks.setAccessible(true);
        Method adapter = packagePrivate(lootEvents.getName(), "generateAdapter");
        for (Object callback : (List<?>) callbacks.get(null)) {
            scan("Pre1_20_5LootTableEventsBridge adapter " + callback, (byte[]) adapter.invoke(null, callback), hits);
        }
        scan("Forge1122LifecycleSynthetics.generateBridge",
                com.retromod.shim.forge.Forge1122LifecycleSynthetics.generateBridge(), hits);
        assertTrue(hits.isEmpty(), String.join("\n", hits));
    }

    /** A class that Retromod ships compiled, as opposed to one generated with ASM. */
    private static boolean isCompiledHelper(String internalName) {
        return GeneratedLogScanTest.class.getClassLoader().getResource(internalName + ".class") != null;
    }

    private static Method packagePrivate(String owner, String name) throws ClassNotFoundException {
        for (Method method : Class.forName(owner).getDeclaredMethods()) {
            if (method.getName().equals(name)) {
                method.setAccessible(true);
                return method;
            }
        }
        throw new AssertionError(owner + " has no method " + name);
    }

    /** Records each read of {@code System.out} or {@code System.err} and each {@code printStackTrace} call. */
    private static void scan(String where, byte[] bytes, List<String> hits) {
        new ClassReader(bytes).accept(new ClassVisitor(Opcodes.ASM9) {
            @Override
            public MethodVisitor visitMethod(int access, String name, String desc, String signature, String[] exceptions) {
                return new MethodVisitor(Opcodes.ASM9) {
                    @Override
                    public void visitFieldInsn(int opcode, String owner, String field, String fieldDesc) {
                        if (owner.equals("java/lang/System") && (field.equals("out") || field.equals("err"))) {
                            hits.add(where + "." + name + " reads System." + field);
                        }
                    }

                    @Override
                    public void visitMethodInsn(int opcode, String owner, String method, String methodDesc, boolean itf) {
                        if (method.equals("printStackTrace")) hits.add(where + "." + name + " calls printStackTrace");
                    }
                };
            }
        }, 0);
    }
}
