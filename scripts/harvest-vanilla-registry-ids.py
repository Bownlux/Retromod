#!/usr/bin/env python3
"""Derive src/main/resources/retromod/vanilla-registry-ids.tsv from one unobfuscated client jar.

Usage:
  python3 -I scripts/harvest-vanilla-registry-ids.py <version> <client.jar> > vanilla-registry-ids.tsv

Give the newest client Retromod builds for (26.3 today). The script only reads the jar as a zip
file. The table lists, per registry, every id the game registers, so the data load gate can tell a
renamed or removed vanilla id from one the host has.

How each registry is read:
  item          one item definition per item under assets/minecraft/items/
  block         one blockstate file per block under assets/minecraft/blockstates/
  entity_type   language keys entity.minecraft.<id> that EntityTypeIds also names
  potion        ids PotionIds names whose language key item.minecraft.potion.effect.<id> exists,
                where long_ and strong_ variants share their base potion's key
  mob_effect    language keys effect.minecraft.<id> that MobEffects also names
  enchantment   one file per enchantment under data/minecraft/enchantment/
  biome         one file per biome under data/minecraft/worldgen/biome/
  structure     one file per structure under data/minecraft/worldgen/structure/
  recipe        one file per recipe under data/minecraft/recipe/, named by its path there
  loot_table    one file per loot table under data/minecraft/loot_table/, named by its path there
  predicate     one file per predicate under data/minecraft/predicate/, named by its path there

The language file keeps keys after their id is gone, which is why the language-based rows also
need the registering class to name the id.
"""
import json
import re
import sys
import zipfile

ID = r"[a-z0-9_]+"


def utf8_constants(data):
    """The CONSTANT_Utf8 strings of one class file."""
    count = int.from_bytes(data[8:10], "big")
    i, index, out = 10, 1, set()
    sizes = {7: 2, 8: 2, 16: 2, 19: 2, 20: 2, 3: 4, 4: 4, 9: 4, 10: 4, 11: 4, 12: 4, 17: 4, 18: 4, 15: 3}
    while index < count:
        tag = data[i]
        i += 1
        if tag == 1:
            length = int.from_bytes(data[i:i + 2], "big")
            out.add(data[i + 2:i + 2 + length].decode("utf-8", "replace"))
            i += 2 + length
        elif tag in (5, 6):
            i += 8
            index += 1
        elif tag in sizes:
            i += sizes[tag]
        else:
            break
        index += 1
    return out


def files(names, folder):
    pattern = re.compile(re.escape(folder) + "(" + ID + r")\.json")
    return {m.group(1) for m in map(pattern.fullmatch, names) if m}


def nested_files(names, folder):
    """Like files, but an id may have a path, as loot tables such as chests/simple_dungeon do."""
    pattern = re.compile(re.escape(folder) + r"([a-z0-9_.-]+(?:/[a-z0-9_.-]+)*)\.json")
    return {m.group(1) for m in map(pattern.fullmatch, names) if m}


def lang_ids(lang, prefix):
    pattern = re.compile(re.escape(prefix) + "(" + ID + ")")
    return {m.group(1) for m in map(pattern.fullmatch, lang) if m}


def main():
    version, path = sys.argv[1], sys.argv[2]
    jar = zipfile.ZipFile(path)
    names = set(jar.namelist())
    lang = json.loads(jar.read("assets/minecraft/lang/en_us.json"))

    def named_by(class_name):
        return utf8_constants(jar.read(class_name))

    registries = {
        "item": files(names, "assets/minecraft/items/"),
        "block": files(names, "assets/minecraft/blockstates/"),
        "entity_type": lang_ids(lang, "entity.minecraft.")
        & named_by("net/minecraft/world/entity/EntityTypeIds.class"),
        "potion": {name for name in named_by("net/minecraft/world/item/alchemy/PotionIds.class")
                   if re.fullmatch(ID, name) and "item.minecraft.potion.effect."
                   + re.sub(r"^(long|strong)_", "", name) in lang},
        "mob_effect": lang_ids(lang, "effect.minecraft.")
        & named_by("net/minecraft/world/effect/MobEffects.class"),
        "enchantment": files(names, "data/minecraft/enchantment/"),
        "biome": files(names, "data/minecraft/worldgen/biome/"),
        "structure": files(names, "data/minecraft/worldgen/structure/"),
        "recipe": nested_files(names, "data/minecraft/recipe/"),
        "loot_table": nested_files(names, "data/minecraft/loot_table/"),
        "predicate": nested_files(names, "data/minecraft/predicate/"),
    }

    print("# registry\tid")
    print("#")
    print("# Every id Minecraft " + version + " registers in the registries mod data names most,")
    print("# generated by scripts/harvest-vanilla-registry-ids.py from the " + version + " client jar.")
    for registry, ids in registries.items():
        for id_ in sorted(ids):
            print(f"{registry}\tminecraft:{id_}")


if __name__ == "__main__":
    main()
